// Generates the Android string resources in all eight languages from
//   - src/i18n.js (server texts: verdicts v.*, findings f.*, patterns pat.*) and
//   - android/i18n/app.json (app texts).
// Run from the repository root:  node android/scripts/gen-strings.mjs
// The output is committed; CI checks that it is up to date (--check).
import fs from "node:fs";
import path from "node:path";
import { fileURLToPath } from "node:url";
import { STRINGS, LANGS } from "../../src/i18n.js";

const here = path.dirname(fileURLToPath(import.meta.url));
const res = path.join(here, "..", "app", "src", "main", "res");
const app = JSON.parse(fs.readFileSync(path.join(here, "..", "i18n", "app.json"), "utf8"));
const SERVER = /^(v|f|pat)\./;

export function resName(key) {
  return "lw_" + key.replace(/[.\-]/g, "_");
}

function esc(s) {
  let out = String(s)
    .replace(/&/g, "&amp;").replace(/</g, "&lt;").replace(/>/g, "&gt;")
    .replace(/\\/g, "\\\\").replace(/'/g, "\\'").replace(/"/g, '\\"').replace(/\n/g, "\\n");
  if (/^[@?]/.test(out)) out = "\\" + out;
  return out;
}

function build(lang) {
  const lines = ['<?xml version="1.0" encoding="utf-8"?>', "<!-- Generated by android/scripts/gen-strings.mjs. Do not edit. -->", "<resources>"];
  const server = Object.keys(STRINGS.en).filter((k) => SERVER.test(k)).sort();
  for (const k of server) {
    const v = STRINGS[lang][k] ?? STRINGS.en[k];
    lines.push(`    <string name="${resName(k)}" formatted="false">${esc(v)}</string>`);
  }
  for (const k of Object.keys(app.en).sort()) {
    const v = app[lang]?.[k];
    if (v == null || v === "") throw new Error(`missing ${lang} ${k}`);
    lines.push(`    <string name="${resName(k)}" formatted="false">${esc(v)}</string>`);
  }
  lines.push("</resources>", "");
  return lines.join("\n");
}

const check = process.argv.includes("--check");
let stale = 0;
for (const lang of LANGS) {
  const dir = path.join(res, lang === "en" ? "values" : `values-${lang}`);
  const file = path.join(dir, "strings_lw.xml");
  const xml = build(lang);
  if (check) {
    if (!fs.existsSync(file) || fs.readFileSync(file, "utf8") !== xml) { console.error("stale: " + file); stale++; }
  } else {
    fs.mkdirSync(dir, { recursive: true });
    fs.writeFileSync(file, xml);
  }
}
if (stale) process.exit(1);
console.log(check ? "strings up to date" : "strings written");
