#!/usr/bin/env node
// Emits the desktop UI strings from src/i18n.js (single source of truth):
//   desktop/ui/i18n.generated.js   — window.LW_I18N for the plain HTML/JS UI
//   desktop/ui/i18n.generated.json — embedded into the Rust core (tray menu, native texts)
// Usage: node desktop/scripts/i18n.mjs [--check]   (--check: exit 1 if the files are stale)
import fs from "node:fs";
import { fileURLToPath } from "node:url";
import { STRINGS, LANGS, LANG_NAMES } from "../../src/i18n.js";

export const PREFIXES = ["dt.", "f.", "pat.", "v.", "stufe.", "age."];

export function build() {
  const strings = {};
  for (const l of LANGS) {
    const d = STRINGS[l] || {};
    const out = {};
    for (const k of Object.keys(d).sort()) if (PREFIXES.some((p) => k.startsWith(p))) out[k] = d[k];
    strings[l] = out;
  }
  const bundle = { langs: LANGS, names: LANG_NAMES, strings };
  const json = JSON.stringify(bundle, null, 1) + "\n";
  const js = "// Generated by desktop/scripts/i18n.mjs from src/i18n.js — do not edit.\n" +
    "window.LW_I18N = " + JSON.stringify(bundle) + ";\n";
  return { json, js };
}

const here = (p) => fileURLToPath(new URL(p, import.meta.url));
export const OUT_JSON = here("../ui/i18n.generated.json");
export const OUT_JS = here("../ui/i18n.generated.js");

if (process.argv[1] && fileURLToPath(import.meta.url) === fs.realpathSync(process.argv[1])) {
  const { json, js } = build();
  if (process.argv.includes("--check")) {
    const stale = [[OUT_JSON, json], [OUT_JS, js]].filter(([f, c]) => !fs.existsSync(f) || fs.readFileSync(f, "utf8") !== c);
    if (stale.length) {
      console.error("stale:", stale.map(([f]) => f).join(", "), "— run: node desktop/scripts/i18n.mjs");
      process.exit(1);
    }
  } else {
    fs.writeFileSync(OUT_JSON, json);
    fs.writeFileSync(OUT_JS, js);
    console.log("wrote", OUT_JSON, OUT_JS);
  }
}
